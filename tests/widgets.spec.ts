test('modal move/resize work with keyboard and pointer; theater remains dismissible', async ({ page }) => {
  await openStory(page, 'components-modal--draggable-and-resizable')
  await page.getByRole('button', { name: 'Edit camera', exact: true }).click()
  const dialog = page.getByRole('dialog')
  const before = await dialog.boundingBox()
  if (!before) throw new Error('Dialog is not visible')
  await page.getByRole('button', { name: 'Move dialog' }).press('ArrowRight')
  expect((await dialog.boundingBox())?.x).toBe(before.x + 10)
  await page.getByRole('button', { name: 'Resize dialog' }).press('ArrowDown')
  expect((await dialog.boundingBox())?.height).toBe(before.height + 10)
  const handle = await page.getByRole('button', { name: 'Resize dialog' }).boundingBox()
  if (!handle) throw new Error('Resize handle is not visible')
  await page.mouse.move(handle.x + handle.width / 2, handle.y + handle.height / 2)
  await page.mouse.down()
  await page.mouse.move(handle.x + handle.width / 2 + 30, handle.y + handle.height / 2 + 30)
  await page.mouse.up()
  expect((await dialog.boundingBox())?.width).toBeGreaterThan(before.width)
  await openStory(page, 'components-modal--theater')
  await page.getByRole('button', { name: 'Open theater' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('button', { name: 'Close dialog' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
})

for (const width of [1280, 390]) {
  test(`public Components page preserves previews, themes and layout at ${width}px`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/components')
    await expect(page.locator('.component-section')).toHaveCount(12)
    const previews = page.locator('.component-demo > .hub-widgets')
    await expect(previews).toHaveCount(12)
    await page.getByLabel('Widget theme').selectOption('dark')
    for (const preview of await previews.all()) await expect(preview).toHaveAttribute('data-hub-theme', 'dark')
    const links = await page.getByRole('link', { name: 'View in Storybook', exact: true }).evaluateAll(anchors => anchors.map(anchor => anchor.getAttribute('href')))
    expect(links).toHaveLength(12)
    for (const link of links) {
      if (!link) throw new Error('A component documentation link is missing its URL')
      const path = new URL(link, 'http://localhost').searchParams.get('path')
      expect(Object.values(index.entries).some(entry => entry.type === 'docs' && path === `/docs/${entry.id}`)).toBe(true)
    }
    const viewport = await page.evaluate(() => ({ scroll: document.documentElement.scrollWidth, width: document.documentElement.clientWidth }))
    expect(viewport.scroll).toBeLessThanOrEqual(viewport.width + 2)
    await page.getByRole('button', { name: 'Selection', exact: true }).click()
    const selected = page.locator('#selection')
    await expect(selected).toBeVisible()
    await page.waitForFunction(() => {
      const section = document.querySelector('#selection')?.getBoundingClientRect()
      const nav = document.querySelector('.components-nav-sticky')?.getBoundingClientRect()
      return section && nav && section.top >= nav.bottom - 2 && section.top < innerHeight
    })
    const trigger = selected.getByRole('button', { name: /^Monitored sites:/ })
    await trigger.scrollIntoViewIfNeeded()
    const scrollBefore = await page.evaluate(() => scrollY)
    await trigger.click()
    await expect(page.getByRole('dialog', { name: 'Choose Monitored sites' })).toBeVisible()
    expect(await page.evaluate(() => scrollY)).toBe(scrollBefore)
    const bounds = await page.getByRole('dialog', { name: 'Choose Monitored sites' }).boundingBox()
    expect(bounds?.x).toBeGreaterThanOrEqual(0)
    expect((bounds?.x ?? 0) + (bounds?.width ?? 0)).toBeLessThanOrEqual(width)
    expect(bounds?.height).toBeLessThan(400)
    await page.screenshot({ path: testInfo.outputPath('selection.png') })
  })
}
