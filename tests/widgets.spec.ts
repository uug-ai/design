test('range handles support keyboard, pointer, exact minutes and midnight', async ({ page }) => {
  await openStory(page, 'components-scheduling--range-slider')
  const start = page.getByRole('slider', { name: 'Recording hours segment 1 start', exact: true })
  await start.press('ArrowRight')
  await expect(start).toHaveAttribute('aria-valuenow', '555')
  const rect = await start.boundingBox()
  if (!rect) throw new Error('Range thumb is not visible')
  await page.mouse.move(rect.x + rect.width / 2, rect.y + rect.height / 2)
  await page.mouse.down()
  await page.mouse.move(rect.x + rect.width / 2 + 60, rect.y + rect.height / 2)
  await page.mouse.up()
  expect(Number(await start.getAttribute('aria-valuenow'))).toBeGreaterThan(555)
  await page.getByRole('slider', { name: 'Recording hours segment 2 start', exact: true }).focus()
  await page.getByRole('button', { name: 'Remove Recording hours segment' }).click()
  await page.getByLabel('Recording hours segment 1 start time', { exact: true }).fill('09:01')
  await page.getByLabel('Recording hours segment 1 end time', { exact: true }).fill('00:00')
  const value = JSON.parse(await page.getByLabel('Schedule value').innerText())
  expect(value).toEqual([{ start: 541, end: 1440 }])
})

