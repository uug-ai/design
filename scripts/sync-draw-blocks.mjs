import { readFile, readdir, mkdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { resolve, join, dirname } from 'node:path'

const root = fileURLToPath(new URL('../', import.meta.url))
const check = process.argv.includes('--check')
const source = resolve(process.argv.find(arg => arg !== '--check' && process.argv.indexOf(arg) > 1) ?? join(root, '../collaborate/web'))
const banner = '// Generated by scripts/sync-draw-blocks.mjs from Draw. Edit the production source, then sync.\n'

async function output(path, content) {
  const destination = join(root, path)
  if (check) {
    if (!(await readFile(destination)).equals(Buffer.from(content))) throw new Error(`Draw snapshot is out of sync: ${path}`)
  } else {
    await mkdir(dirname(destination), { recursive: true })
    await writeFile(destination, content)
  }
}

for (const name of ['blocks.ts', 'isoIcons.ts', 'types.ts', 'text.ts', 'components/BlockView.tsx']) {
  const original = await readFile(join(source, 'src', name), 'utf8')
  const content = original
    .replaceAll("from '../blocks'", "from './blocks'")
    .replaceAll("from '../text'", "from './text'")
    .replaceAll("from '../types'", "from './types'")
    .replaceAll('/cloud/', '/draw-blocks/cloud/')
    .replaceAll('/kubernetes/', '/draw-blocks/kubernetes/')
    .replaceAll('/generic/', '/draw-blocks/generic/')
    .replaceAll('/badges/', '/draw-blocks/badges/')
  await output(`src/components/DrawBlocks/production/${name.replace('components/', '')}`, banner + content)
}

const css = await readFile(join(source, 'src/index.css'), 'utf8')
function variables(selector) {
  const body = css.slice(css.indexOf(selector) + selector.length).split('\n}')[0]
  const declarations = body.match(/^\s+--[\w-]+:[^\n]+/gm)
  if (!declarations) throw new Error(`Missing Draw palette: ${selector}`)
  return declarations.filter(line => /--(?:block-|iso-|background:|surface:|surface-strong:|text-primary:|canvas:)/.test(line)).join('\n')
}
const dark = ".draw-block-preview[data-draw-theme='dark'],\n[data-theme='dark'] .draw-block-preview:not([data-draw-theme='light']),\n[data-hub-theme='dark'] .draw-block-preview:not([data-draw-theme='light'])"
const rules = ['block-card', 'block-title', 'block-subtitle', 'block-shadow'].map(name => {
  const rule = css.match(new RegExp(`\\.${name} \\{[^}]+\\}`))?.[0]
  if (!rule) throw new Error(`Missing Draw rule: ${name}`)
  return `.draw-block-preview ${rule}`
})
await output('src/components/DrawBlocks/production/blocks.css',
  `/* Generated from Draw's production palettes and block styles. */\n.draw-block-preview {\n${variables(':root {')}\n}\n${dark} {\n${variables(":root[data-theme='dark'] {")}\n}\n${rules.join('\n')}\n`)

let assets = 0
for (const directory of ['badges', 'cloud', 'generic', 'kubernetes']) {
  for (const entry of await readdir(join(source, 'public', directory), { withFileTypes: true })) {
    if (!entry.isFile()) throw new Error(`Unexpected nested Draw asset: ${directory}/${entry.name}`)
    await output(`public/draw-blocks/${directory}/${entry.name}`, await readFile(join(source, 'public', directory, entry.name)))
    assets++
  }
}
console.log(`${check ? 'Verified' : 'Synchronized'} Draw renderer, catalogue, palettes and ${assets} local assets.`)
